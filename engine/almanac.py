    idx = _gz_index(day_gz)
    ri_zhi = day_gz[1]
    chong_zhi = C.ZHI_CHONG[ri_zhi]
    chong_gz = GANZHI60[(idx + 6) % 60]
    ju = C.ZHI_SANHE[ri_zhi]                     # 日支所属三合局五行
    sha = SHA_FANG_BY_JU[ju]
    return {
        "zhi": chong_zhi,
        "shengxiao": C.ZHI_SHENGXIAO[chong_zhi],
        "sha": sha,
        "text": "冲%s(%s)煞%s" % (C.ZHI_SHENGXIAO[chong_zhi], chong_gz, sha),
        "chong_ganzhi": chong_gz,
        "ju": ju,
    }


