def _jie_date(year: int, name: str, lon: float) -> datetime.date:
    """某「节」的北京日期：优先 calendar_cn.jie_datetime（VSOP87 精度），
    否则用内置 Meeus 低精度节气（约 ±15 分钟，临界日可能差一日）。带缓存。"""
    key = (year, name)
    if key in _JIE_CACHE:
        return _JIE_CACHE[key]
    mod = _calendar_cn()
    fn = getattr(mod, "jie_datetime", None) if mod is not None else None
    out = None
    if callable(fn):
        try:
            dt = fn(year, name)
        except Exception:
            dt = None
        if isinstance(dt, datetime.datetime):
            out = dt.date()
        elif isinstance(dt, datetime.date):
            out = dt
    if out is None:
        out = _term_date(year, lon)
    _JIE_CACHE[key] = out
    return out


def _fallback_month_gz(d: datetime.date, year_gz: str):
    """返回 (月柱干支, 节名, 月支)：以最近一个「节」定月建，五虎遁定月干。"""
    cands = []
    for y in (d.year - 1, d.year):
        for lon, name, zhi in JIE_LON_ZHI:
            cands.append((_jie_date(y, name, lon), name, zhi))
    passed = [c for c in cands if c[0] <= d]
    if not passed:
        raise ValueError("无法定位节气（%s）" % d)
    jie_date, jie_name, yue_zhi = max(passed, key=lambda c: c[0])
    n = ZHI_INDEX[yue_zhi] - ZHI_INDEX["寅"]          # 距寅月的月序 0..11
    if n < 0:
        n += 12
    yue_gan = (GAN_INDEX[year_gz[0]] * 2 + 2 + n) % 10  # 五虎遁
    return GAN[yue_gan] + yue_zhi, jie_name, yue_zhi


def _fallback_year_gz(d: datetime.date) -> str:
    """立春为界之年柱（八字/择日年柱）：立春（黄经 315°）前属上一年。"""
    lichun = _term_date(d.year, 315)
    y = d.year if d >= lichun else d.year - 1
    return GANZHI60[(y - 4) % 60]


_SILI_LONS = [(0, "春分"), (90, "夏至"), (180, "秋分"), (270, "冬至")]
_SIJUE_LONS = [(315, "立春"), (45, "立夏"), (135, "立秋"), (225, "立冬")]


def _is_sili_sijue(d: datetime.date):
    """四离日（二分二至前一日）、四绝日（四立前一日），忌出行嫁娶开市动土。"""
    nxt = d + datetime.timedelta(days=1)
    for y in (d.year - 1, d.year):
        for lon, name in _SILI_LONS:
            if _jie_date(y, name, lon) == nxt:
                return "四离日（%s前一日）" % name
        for lon, name in _SIJUE_LONS:
            if _jie_date(y, name, lon) == nxt:
                return "四绝日（%s前一日）" % name
    return None


