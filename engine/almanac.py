def evaluate_shensha(d: datetime.date, day_gz: str, year_gz: str, month_gz: str,
                     kong: list) -> dict:
    """评估当日值日神煞。

    返回 {"items": [{"name","type","note"}], "ji_shen": set, "xiong_sha": set}。
    每条 note 写明该煞的判定规则与出处类别，便于人工复核。
    """
    ri_gan, ri_zhi = day_gz[0], day_gz[1]
    yue_zhi, nian_zhi = month_gz[1], year_gz[1]
    season = SEASON_OF_JIE[yue_zhi]
    ju = C.ZHI_SANHE[yue_zhi]          # 月支所属三合局五行
    items, ji_shen, xiong_sha = [], set(), set()

    def add(name, kind, note):
        items.append({"name": name, "type": kind, "note": note})
        (ji_shen if kind == "吉" else xiong_sha).add(name)

    # ---- 吉神 -----------------------------------------------------------
    td = TIAN_DE[yue_zhi]                                  # 天德（月支见干或支）
    if td == ri_gan or td == ri_zhi:
        add("天德", "吉", "天德：%s月见%s（《协纪辨方书》天德表：正月丁、二月申、"
                         "三月壬…十二月庚），宜祭祀祈福、解厄赦罪" % (yue_zhi, td))
    td_he = GAN_HE[td] if td in GAN_HE else C.ZHI_LIUHE[td]
    if td_he == ri_gan or td_he == ri_zhi:
        add("天德合", "吉", "天德合：天德%s所合之%s值日，吉同天德而力减" % (td, td_he))
    yd = C.WUXING_GAN[ju][0]                               # 月德（三合局阳干）
    if yd == ri_gan:
        add("月德", "吉", "月德：%s月（%s局）见%s（三合局取阳干为月德），"
                         "宜祭祀祈福、婚嫁开市" % (yue_zhi, ju, yd))
    yd_he = GAN_HE[yd]
    if yd_he == ri_gan:
        add("月德合", "吉", "月德合：月德%s所合之%s值日，吉" % (yd, yd_he))
    if TIAN_SHE[yue_zhi] == day_gz:
        add("天赦", "吉", "天赦：%s月见%s日（口诀「春戊寅、夏甲午、秋戊申、冬甲子」），"
                          "宜祭祀祈福、赦罪解冤" % (yue_zhi, day_gz))
    if TIAN_YUAN[yue_zhi] == day_gz:
        add("天愿", "吉", "天愿（存疑）：%s月见%s日（正月乙亥…十二月甲子），"
                          "宜婚嫁开市纳财" % (yue_zhi, day_gz))
    if TIAN_XI_SEASON[season] == ri_zhi:
        add("天喜", "吉", "天喜（存疑）：%s见%s（一说春戌夏丑秋辰冬未），"
                          "宜婚嫁、纳采、会友" % (season, ri_zhi))
    if C.ZHI_SANHE[ri_zhi] == ju and ri_zhi != yue_zhi:
        add("三合", "吉", "三合：日支%s与月建%s同属%s局，宜会友、婚嫁、开市、立券"
                          % (ri_zhi, yue_zhi, ju))
    if C.ZHI_LIUHE[ri_zhi] == yue_zhi:
        add("六合", "吉", "六合：日支%s与月建%s六合，宜和合之事（婚嫁、交易、修造）"
                          % (ri_zhi, yue_zhi))

    # ---- 凶煞 -----------------------------------------------------------
    if C.ZHI_CHONG[yue_zhi] == ri_zhi:
        add("月破", "凶", "月破：日支%s冲月建%s，为「月破」大耗之日，诸事不宜，"
                          "唯宜破屋坏垣、求医解除" % (ri_zhi, yue_zhi))
    if C.ZHI_CHONG[nian_zhi] == ri_zhi:
        add("岁破", "凶", "岁破：日支%s冲太岁%s（年支），忌嫁娶、动土、开市等大事"
                          % (ri_zhi, nian_zhi))
    if day_gz in SI_FEI[season]:
        add("四废", "凶", "四废：%s之%s日（当季五行处「绝」地者，春庚申辛酉、"
                          "夏壬子癸亥、秋甲寅乙卯、冬丙午丁巳），百事不宜" % (season, day_gz))
    if SHOU_SI[yue_zhi] == ri_zhi:
        add("受死", "凶", "受死（存疑）：%s月受死日在%s，忌嫁娶、安葬、远行" % (yue_zhi, ri_zhi))
    if WANG_WANG[yue_zhi] == ri_zhi:
        add("往亡", "凶", "往亡（存疑）：%s月往亡在%s，忌出行、赴任、嫁娶" % (yue_zhi, ri_zhi))
    if GUI_JI[yue_zhi] == ri_zhi:
        add("归忌", "凶", "归忌（存疑）：孟月丑、仲月寅、季月子，%s月（%s）归忌在%s，"
                          "忌移徙、归家" % (yue_zhi, "孟" if yue_zhi in "寅巳申亥" else
                                          ("仲" if yue_zhi in "卯午酉子" else "季"), ri_zhi))
    if C.ZHI_XING[yue_zhi] == ri_zhi:
        add("月刑", "凶", "月刑：%s月刑在%s（月支三刑），忌兴工动土、词讼"
                          % (yue_zhi, ri_zhi))
    if C.ZHI_HAI[yue_zhi] == ri_zhi:
        add("月害", "凶", "月害：%s月害在%s（月支六害），忌婚嫁、兴工" % (yue_zhi, ri_zhi))
    if ri_zhi == _jue_zhi(ju):
        add("劫煞", "凶", "劫煞：%s局（%s月）之绝地在%s，忌出行、动土、开仓"
                          % (ju, yue_zhi, ri_zhi))
    if ri_zhi == _tai_zhi(ju):
        add("灾煞", "凶", "灾煞：%s局（%s月）之胎地在%s，忌兴工、远行、求财"
                          % (ju, yue_zhi, ri_zhi))
    if ri_zhi in ("巳", "亥"):
        add("重日", "凶", "重日：巳、亥为「重日」（日月同建），忌安葬、破土、成服")
    if yue_zhi in kong:
        add("月建空亡", "凶", "月建空亡：月建%s落日柱旬空%s，本月建之事减力，"
                              "不宜作为择日主依据" % (yue_zhi, kong))
    silue = _is_sili_sijue(d)
    if silue:
        add("四离四绝", "凶", "%s（节气前一日），忌出行、嫁娶、开市、动土（存疑："
                              "以近似节气推算，临界日可能差一日）" % silue)

    return {"items": items, "ji_shen": ji_shen, "xiong_sha": xiong_sha}


