_CC_STATE = {"mod": None, "tried": False}
_CC_LUNAR_NAMES = ("lunar_from_date", "lunar_date", "solar_to_lunar", "lunar_of",
                   "lunar_info", "get_lunar", "lunar", "to_lunar")
