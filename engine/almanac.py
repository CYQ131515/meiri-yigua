def derive_yiji(ctx: dict):
    """由规则组合推导宜/忌。

    ctx 键：jc(建除名)、xiu(宿名)、xiu_jx(吉/凶)、ji_shen(set)、xiong_sha(set)、
            pengzu_terms(dict 用词→彭祖原文)、kong(list)
    判定顺序（可解释、可复核）：
      1) 命中「硬忌」凶煞（月破/岁破/四废/受死/往亡/重日/四离四绝）或彭祖对应忌条
         → 判「忌」（一票否决）；
      2) 否则比较命中数：忌条件 ≥2 且不少于宜条件 → 「忌」；
         宜条件 ≥2 且无忌条件 → 「宜」；宜 ≥3 且忌 =1 → 「宜」（弱）；
         仅宜 =1 且无忌 → 记为「宜(弱)」，仅在宜项不足时补位。
    返回 (yi, ji, yi_detail, ji_detail)。
    """
    yi_strong, yi_weak, ji_list, ji_weak = [], [], [], []
    yi_detail, ji_detail = [], []
    for term, r in TERMS.items():
        hit_yi, reason_yi = [], []
        hit_ji, reason_ji = [], []
        if ctx["jc"] in r["jc_yi"]:
            hit_yi.append("建除"); reason_yi.append("建除『%s』日通书宜%s" % (ctx["jc"], term))
        if r["xiu_yi"] and ctx["xiu_jx"] == "吉":
            hit_yi.append("宿"); reason_yi.append("值吉宿%s" % ctx["xiu"])
        for s in r["shen_yi"]:
            if s in ctx["ji_shen"]:
                hit_yi.append(s); reason_yi.append("吉神『%s』在位" % s)
        if ctx["jc"] in r["jc_ji"]:
            hit_ji.append("建除"); reason_ji.append("建除『%s』日不宜%s" % (ctx["jc"], term))
        if r["xiu_ji"] and ctx["xiu_jx"] == "凶":
            hit_ji.append("宿"); reason_ji.append("值凶宿%s" % ctx["xiu"])
        for s in r["shen_ji"]:
            if s in ctx["xiong_sha"]:
                hit_ji.append(s); reason_ji.append("凶煞『%s』值日" % s)
        pz_hit = [p for p in r["pengzu_ji"] if ctx["pengzu_terms"].get(term) == p]
        if pz_hit:
            hit_ji.append("彭祖")
            reason_ji.append("彭祖百忌『%s』（%s日）" % (pz_hit[0], pz_hit[0][0]))
        hard = bool(pz_hit) or any(s in HARD_JI_SHENSHA for s in hit_ji)
        ny, nj = len(hit_yi), len(hit_ji)
        if hard:
            ji_detail.append({"item": term, "reason": "；".join(reason_ji) +
                              "（硬忌，一票否决）", "basis": r["basis"]})
        elif nj >= 2 and nj >= ny:
            ji_detail.append({"item": term, "reason": "；".join(reason_ji), "basis": r["basis"]})
        elif ny >= 2 and nj == 0:
            yi_detail.append({"item": term, "reason": "；".join(reason_yi), "basis": r["basis"]})
        elif ny >= 3 and nj == 1:
            yi_detail.append({"item": term, "reason": "；".join(reason_yi) +
                              "（另有轻微不宜：%s）" % "、".join(reason_ji), "basis": r["basis"]})
        elif ny == 1 and nj == 0:
            yi_weak.append({"item": term, "reason": "；".join(reason_yi) + "（次要）",
                            "basis": r["basis"]})
        elif nj == 1 and ny == 0:
            tag = "（软忌，仅作参考）" if all(s in SOFT_JI_SHENSHA for s in hit_ji) else "（次要）"
            ji_weak.append({"item": term, "reason": "；".join(reason_ji) + tag,
                            "basis": r["basis"]})
    hard_day = any(s in ctx["xiong_sha"] for s in RELIEF_SHENSHA)
    if hard_day:                      # 大凶之日：通书仅许破旧除病与日常小事
        added = 0
        for t in RELIEF_TERMS:
            if added >= 3 or len(yi_detail) >= 6:
                break
            if any(x["item"] == t for x in yi_detail) or any(x["item"] == t for x in yi_weak):
                continue
            yi_detail.insert(0, {"item": t, "reason": RELIEF_REASON,
                                 "basis": TERMS[t]["basis"]})
            added += 1
    yi_detail.sort(key=lambda x: (0 if x["reason"] == RELIEF_REASON else 1,
                                  -len(x["reason"])))
    yi = [x["item"] for x in yi_detail][:14]
    ji = [x["item"] for x in ji_detail][:14]
    if len(yi) < 8:
        for x in yi_weak:
            if x["item"] not in yi and len(yi) < 8:
                yi.append(x["item"]); yi_detail.append(x)
    if len(ji) < 6:
        for x in ji_weak:
            if x["item"] not in ji and len(ji) < 8:
                ji.append(x["item"]); ji_detail.append(x)
    yi_detail = [x for x in yi_detail if x["item"] in yi]
    ji_detail = [x for x in ji_detail if x["item"] in ji]
    return yi, ji, yi_detail, ji_detail


