def _selfcheck_lunar() -> list:
    """降级农历算法自检：春节与闰月朔日（与传统历书核对过的常见年份）。"""
    cases = [
        (datetime.date(2024, 2, 10), 1, 1, False, "2024 春节（甲辰年正月初一）"),
        (datetime.date(2025, 1, 29), 1, 1, False, "2025 春节（乙巳年正月初一）"),
        (datetime.date(2026, 2, 17), 1, 1, False, "2026 春节（丙午年正月初一）"),
        (datetime.date(2023, 3, 22), 2, 1, True, "2023 闰二月初一"),
        (datetime.date(2025, 7, 25), 6, 1, True, "2025 闰六月初一"),
    ]
    out = []
    for d, m, dd, leap, label in cases:
        got = _fallback_lunar(d)
        ok = bool(got) and (got["lunar_month"], got["lunar_day"], got["is_leap"]) == (m, dd, leap)
        out.append((label, ok, got))
    return out


def _selfcheck_tables() -> list:
    """规则表内部一致性自检：引用合法、彭祖 22 条闭环、表长与覆盖完整。"""
    errs = []
    pz_all = set(PENGZU_GAN.values()) | set(PENGZU_ZHI.values())
    if len(pz_all) != 22:
        errs.append("彭祖条数 %d ≠ 22" % len(pz_all))
    known_ji = set(JI_SHEN_ALL) | {"天德合", "月德合"}
    known_xiong = set(HARD_JI_SHENSHA) | set(SOFT_JI_SHENSHA) | {"月建空亡"}
    for t, r in TERMS.items():
        if not r["basis"] or len(r["basis"]) < 20:
            errs.append("TERMS[%s].basis 过短" % t)
        if not (r["jc_yi"] or r["jc_ji"] or r["shen_yi"] or r["shen_ji"]
                or r["pengzu_ji"] or r["xiu_yi"]):
            errs.append("TERMS[%s] 无规则条件" % t)
        errs += ["TERMS[%s] 非法建除名 %s" % (t, n)
                 for n in list(r["jc_yi"]) + list(r["jc_ji"]) if n not in JIANCHU_NAMES]
        errs += ["TERMS[%s] 未知吉神 %s" % (t, s) for s in r["shen_yi"]
                 if s not in known_ji]
        errs += ["TERMS[%s] 未知凶煞 %s" % (t, s) for s in r["shen_ji"]
                 if s not in known_xiong]
        for ph in r["pengzu_ji"]:
            if ph not in pz_all or PENGZU_TERM.get(ph) != t:
                errs.append("TERMS[%s] 彭祖条目映射不一致: %s" % (t, ph))
    for ph in pz_all:
        if ph not in PENGZU_TERM or PENGZU_TERM[ph] not in TERMS:
            errs.append("彭祖原文未映射到用词: %s" % ph)
    if any(len(x) != 28 for x in (XIU_28, XIU_JIXIONG, XIU_QIN, XIU_GONG)):
        errs.append("二十八宿表长度错误")
    for g in GAN:
        for tbl in (XISHEN, CAISHEN, FUSHEN, GUI_REN):
            if g not in tbl:
                errs.append("方位/贵人表缺日干 %s" % g)
    for z in ZHI:
        for tbl in (TIAN_DE, TIAN_SHE, TIAN_YUAN, SHOU_SI, WANG_WANG, GUI_JI,
                    QINGLONG_START):
            if z not in tbl:
                errs.append("神煞/时辰表缺支 %s" % z)
    if any(len(v) != 2 for v in SI_FEI.values()):
        errs.append("四废表异常")
    if len(RELIEF_TERMS) < 3 or any(t not in TERMS for t in RELIEF_TERMS):
        errs.append("缓释用词表异常")
    head = ("规则表内部一致性（建除/神煞引用合法、彭祖 22 条闭环、表长与覆盖齐全，"
            "问题 %d 例）" % len(errs))
    return [(head, not errs)] + [("规则表问题：" + e, False) for e in errs[:5]]


