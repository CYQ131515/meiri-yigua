# 方角用词沿用通俗方位名（正东/正南/东南…），由地支落宫换算，见 ZHI_FANGWEI。


def jdn_of(year: int, month: int, day: int) -> int:
    """公历 → 儒略日序（JDN，正午为整数时刻；Fliegel-Van Flandern 公式）。"""
    a = (14 - month) // 12
    y = year + 4800 - a
    m = month + 12 * a - 3
    return day + (153 * m + 2) // 5 + 365 * y + y // 4 - y // 100 + y // 400 - 32045


def jdn_of_date(d: datetime.date) -> int:
    return jdn_of(d.year, d.month, d.day)


def weekday_index(jdn: int) -> int:
    """0=星期日 … 6=星期六。JDN mod 7 = 5 为星期六（用 2026-10-17 星期六核对）。"""
    return (jdn + 1) % 7


def _gz_index(gz: str) -> int:
    """干支字符串 → 六十甲子序号 0..59（同时校验合法性）。"""
    if not isinstance(gz, str) or len(gz) != 2:
        raise ValueError("干支字符串必须是两个汉字，例如 '丙寅'")
    g, z = gz[0], gz[1]
    if g not in GAN_INDEX or z not in ZHI_INDEX:
        raise ValueError("非法干支：%s" % gz)
    idx = GAN_INDEX[g]
    # 该天干在六十甲子中出现于 idx, idx+10, …，取地支匹配者
    for cand in range(idx, 60, 10):
        if cand % 12 == ZHI_INDEX[z]:
            return cand
    raise ValueError("干支组合不存在于六十甲子中：%s" % gz)


